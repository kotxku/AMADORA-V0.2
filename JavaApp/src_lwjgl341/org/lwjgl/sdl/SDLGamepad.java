    private static final int PAD = 1, AXES = 6, BUTTONS = 15; // SOUTH..DPAD_RIGHT

    // Fills SDL-ordered axes (-1..1, y down) and buttons when arrays are given; false when no controller is connected
    private static native boolean nativeGamepadState(float[] axes, byte[] buttons);

    private static boolean state(float[] axes, byte[] buttons) {
        try {
            return nativeGamepadState(axes, buttons);
        } catch (UnsatisfiedLinkError e) { // desktop tests
            return false;
        }
    }

    public static boolean SDL_HasGamepad() { return state(null, null); }

    // Freed with SDL_free like a real list, so it comes from LWJGL's allocator
    public static IntBuffer SDL_GetGamepads() {
        IntBuffer ids = memAllocInt(1);
        if (SDL_HasGamepad()) ids.put(0, PAD);
        else ids.limit(0);
        return ids;
    }

    public static boolean SDL_IsGamepad(int id) { return id == PAD && SDL_HasGamepad(); }

    public static long SDL_OpenGamepad(int id) { return SDL_IsGamepad(id) ? PAD : 0L; }

    public static boolean SDL_GamepadConnected(long gamepad) { return gamepad == PAD && SDL_HasGamepad(); }

    public static void SDL_CloseGamepad(long gamepad) {}

    public static void SDL_UpdateGamepads() {}

    public static java.lang.String SDL_GetGamepadName(long gamepad) { return gamepad == PAD ? "iOS controller" : null; }

    public static short SDL_GetGamepadAxis(long gamepad, int axis) {
        float[] axes = new float[AXES];
        if (gamepad != PAD || axis < 0 || axis >= AXES || !state(axes, new byte[BUTTONS])) return 0;
        return (short) Math.max(-32768, Math.min(32767, Math.round(axes[axis] * 32767f)));
    }

    public static boolean SDL_GetGamepadButton(long gamepad, int button) {
        byte[] buttons = new byte[BUTTONS];
        return gamepad == PAD && button >= 0 && button < BUTTONS && state(new float[AXES], buttons) && buttons[button] != 0;
    }

