    public static int SDL_DEFINE_PIXELFOURCC(byte a, byte b, byte c, byte d) {
        return (a & 0xFF) | (b & 0xFF) << 8 | (c & 0xFF) << 16 | (d & 0xFF) << 24;
    }

    public static int SDL_DEFINE_PIXELFORMAT(int type, int order, int layout, int bits, int bytes) {
        return 1 << 28 | type << 24 | order << 20 | layout << 16 | bits << 8 | bytes;
    }

    public static int SDL_PIXELFLAG(int format) { return format >> 28 & 0x0F; }
    public static int SDL_PIXELTYPE(int format) { return format >> 24 & 0x0F; }
    public static int SDL_PIXELORDER(int format) { return format >> 20 & 0x0F; }
    public static int SDL_PIXELLAYOUT(int format) { return format >> 16 & 0x0F; }

    public static boolean SDL_ISPIXELFORMAT_FOURCC(int format) {
        return format != 0 && SDL_PIXELFLAG(format) != 1;
    }

    public static int SDL_BITSPERPIXEL(int format) {
        return SDL_ISPIXELFORMAT_FOURCC(format) ? 0 : format >> 8 & 0xFF;
    }

    public static int SDL_BYTESPERPIXEL(int format) {
        if (!SDL_ISPIXELFORMAT_FOURCC(format)) return format & 0xFF;
        // YUY2, UYVY, YVYU and P010 use two bytes per pixel, the other FourCC formats one
        return format == 844715353 || format == 1498831189 || format == 1431918169 || format == 808530000 ? 2 : 1;
    }

    // Pixel types: INDEX1 1, INDEX4 2, INDEX8 3, PACKED8-32 4-6, ARRAYU8-ARRAYF32 7-11, INDEX2 12
    public static boolean SDL_ISPIXELFORMAT_INDEXED(int format) {
        int type = SDL_PIXELTYPE(format);
        return !SDL_ISPIXELFORMAT_FOURCC(format) && (type == 1 || type == 2 || type == 3 || type == 12);
    }

    public static boolean SDL_ISPIXELFORMAT_PACKED(int format) {
        int type = SDL_PIXELTYPE(format);
        return !SDL_ISPIXELFORMAT_FOURCC(format) && type >= 4 && type <= 6;
    }

    public static boolean SDL_ISPIXELFORMAT_ARRAY(int format) {
        int type = SDL_PIXELTYPE(format);
        return !SDL_ISPIXELFORMAT_FOURCC(format) && type >= 7 && type <= 11;
    }

    public static boolean SDL_ISPIXELFORMAT_FLOAT(int format) {
        int type = SDL_PIXELTYPE(format);
        return !SDL_ISPIXELFORMAT_FOURCC(format) && (type == 10 || type == 11);
    }

    public static boolean SDL_ISPIXELFORMAT_10BIT(int format) {
        return !SDL_ISPIXELFORMAT_FOURCC(format) && SDL_PIXELTYPE(format) == 6 && SDL_PIXELLAYOUT(format) == 7;
    }

    // Packed orders ARGB 3, RGBA 4, ABGR 7, BGRA 8; array orders RGBA 2, ARGB 3, BGRA 5, ABGR 6
    public static boolean SDL_ISPIXELFORMAT_ALPHA(int format) {
        int order = SDL_PIXELORDER(format);
        if (SDL_ISPIXELFORMAT_PACKED(format)) return order == 3 || order == 4 || order == 7 || order == 8;
        if (SDL_ISPIXELFORMAT_ARRAY(format)) return order == 2 || order == 3 || order == 5 || order == 6;
        return false;
    }

