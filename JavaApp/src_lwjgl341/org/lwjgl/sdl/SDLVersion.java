package org.lwjgl.sdl;

public final class SDLVersion {
    private SDLVersion() {}

    public static final int SDL_VERSION = 3004001; // SDL_VERSIONNUM(3, 4, 1)

    public static int SDL_VERSIONNUM(int major, int minor, int patch) {
        return major * 1000000 + minor * 1000 + patch;
    }

    public static int SDL_VERSIONNUM_MAJOR(int version) { return version / 1000000; }
    public static int SDL_VERSIONNUM_MINOR(int version) { return version / 1000 % 1000; }
    public static int SDL_VERSIONNUM_MICRO(int version) { return version % 1000; }

    public static boolean SDL_VERSION_ATLEAST(int major, int minor, int patch) {
        return SDL_GetVersion() >= SDL_VERSIONNUM(major, minor, patch);
    }

    public static int SDL_GetVersion() {
        return SDL_VERSIONNUM(3, 4, 1);
    }

    public static String SDL_GetRevision() {
        return "AMADORA iOS bridge";
    }

    // ---- GENERATED by tools/sdl_bridge_gen/gen_sdl_fallbacks.py: do not edit below ----
    public static final int SDL_MAJOR_VERSION = 3;
    public static final int SDL_MINOR_VERSION = 4;
    public static final int SDL_MICRO_VERSION = 14;

    public static long nSDL_GetRevision() { AmadoraSDL.unsupported("nSDL_GetRevision"); return 0L; }
    // ---- END GENERATED ----
}
