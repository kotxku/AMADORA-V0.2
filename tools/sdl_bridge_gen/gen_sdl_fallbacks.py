#!/usr/bin/env python3
"""Fill in the rest of the SDL3 API for AMADORA's iOS SDL bridge (JavaApp/src_lwjgl341/org/lwjgl/sdl).

There is no libSDL3 on iOS, so every LWJGL SDL function class Minecraft or a mod can call has to be replaced by a
Java class; an official one left in place throws as soon as it looks up a native function, and a replaced one that
lacks a method throws NoSuchMethodError. For every function class in the official binding this writes, between the
GENERATED markers of our class (or into a new file), each public constant and each public static method that the
hand-written part doesn't define. The methods log once and return false/0/null, which callers treat as "not
supported". Hand-written code stays outside the markers and always wins.

usage: gen_sdl_fallbacks.py <signatures jar> <runtime jar>[;<runtime jar>...] <javac>
  signatures jar: the lwjgl-sdl the game and mods are compiled against (e.g. lwjgl-sdl-3.4.3.jar)
  runtime jars:   what the app ships (JavaApp/lwjgl341/*.jar); methods using a type missing there are skipped
Run from the repository root. Needs javac to compile the hand-written classes first.
"""
import os, re, shutil, struct, subprocess, sys, tempfile, zipfile

SRC = 'JavaApp/src_lwjgl341/org/lwjgl/sdl'
BEGIN = '    // ---- GENERATED by tools/sdl_bridge_gen/gen_sdl_fallbacks.py: do not edit below ----'
END = '    // ---- END GENERATED ----'
HEADER = '''/*
 * AMADORA: SDL3 on top of Amethyst's iOS GLFW layer, see AmadoraSDL. No hand-written behaviour yet: every member below
 * is generated, so calls into this part of SDL return "not supported" instead of looking for a missing libSDL3.
 */
package org.lwjgl.sdl;

public final class %s {
    private %s() {}

%s
%s
%s
}
'''

ACC_PUBLIC, ACC_STATIC, ACC_SYNTHETIC = 0x1, 0x8, 0x1000


def parse_class(data):
    """(constants, methods, referenced class names) of a class file; constants: name -> (descriptor, value)."""
    n = struct.unpack('>H', data[8:10])[0]
    i, k, cp = 10, 1, [None] * n
    while k < n:
        t = data[i]
        if t == 1:
            l = struct.unpack('>H', data[i + 1:i + 3])[0]
            cp[k] = data[i + 3:i + 3 + l].decode('utf8', 'replace'); i += 3 + l
        elif t == 3: cp[k] = struct.unpack('>i', data[i + 1:i + 5])[0]; i += 5
        elif t == 4: cp[k] = struct.unpack('>f', data[i + 1:i + 5])[0]; i += 5
        elif t == 5: cp[k] = struct.unpack('>q', data[i + 1:i + 9])[0]; i += 9; k += 1
        elif t == 6: cp[k] = struct.unpack('>d', data[i + 1:i + 9])[0]; i += 9; k += 1
        elif t in (7, 8, 16, 19, 20): cp[k] = ('ref', t, struct.unpack('>H', data[i + 1:i + 3])[0]); i += 3
        elif t in (9, 10, 11, 12, 17, 18): i += 5
        elif t == 15: i += 4
        else: raise ValueError(t)
        k += 1
    i += 6
    i += 2 + 2 * struct.unpack('>H', data[i:i + 2])[0]

    def members(i, fields):
        out = []
        count = struct.unpack('>H', data[i:i + 2])[0]; i += 2
        for _ in range(count):
            acc, ni, di, ac = struct.unpack('>HHHH', data[i:i + 8]); i += 8
            value = None
            for _ in range(ac):
                an, al = struct.unpack('>HI', data[i:i + 6])
                if fields and cp[an] == 'ConstantValue':
                    v = cp[struct.unpack('>H', data[i + 6:i + 8])[0]]
                    value = cp[v[2]] if isinstance(v, tuple) else v  # a String constant points at its Utf8
                i += 6 + al
            out.append((acc, cp[ni], cp[di], value))
        return i, out

    i, fields = members(i, True)
    i, methods = members(i, False)
    return fields, methods


def desc_types(desc):
    """Java source types of a method descriptor: ([params], return)."""
    def one(s, j):
        dims = 0
        while s[j] == '[': dims += 1; j += 1
        c = s[j]
        if c == 'L':
            e = s.index(';', j)
            name = s[j + 1:e].replace('/', '.').replace('$', '.'); j = e + 1
        else:
            name = {'I': 'int', 'J': 'long', 'Z': 'boolean', 'B': 'byte', 'S': 'short', 'C': 'char',
                    'F': 'float', 'D': 'double', 'V': 'void'}[c]; j += 1
        return name + '[]' * dims, j
    params, j = [], 1
    while desc[j] != ')':
        t, j = one(desc, j); params.append(t)
    return params, one(desc, j + 1)[0]


def class_refs(desc):
    return [m.replace('/', '.') for m in re.findall(r'L([^;]+);', desc)]


def literal(desc, v):
    if desc == 'Ljava/lang/String;':
        return '"' + v.replace('\\', '\\\\').replace('"', '\\"') + '"'
    if desc == 'J': return '%dL' % v
    if desc in ('F', 'D'):
        suffix = 'f' if desc == 'F' else 'd'
        if v != v: return ('Float' if desc == 'F' else 'Double') + '.NaN'
        if v in (float('inf'), float('-inf')):
            return ('' if v > 0 else '-') + ('Float' if desc == 'F' else 'Double') + '.POSITIVE_INFINITY'
        return repr(v) + suffix
    if desc == 'Z': return 'true' if v else 'false'
    if desc == 'C': return '(char) %d' % v
    if desc == 'B': return '(byte) %d' % v
    if desc == 'S': return '(short) %d' % v
    return str(v)


DEFAULTS = {'boolean': 'false', 'int': '0', 'long': '0L', 'float': '0f', 'double': '0d',
            'byte': '(byte) 0', 'short': '(short) 0', 'char': "'\\0'"}


def main():
    sig_jar, runtime, javac = sys.argv[1], sys.argv[2].split(os.pathsep), sys.argv[3]
    known = set()
    for jar in runtime:
        with zipfile.ZipFile(jar) as z:
            known.update(n[:-6].replace('/', '.') for n in z.namelist() if n.endswith('.class'))

    def available(name):
        return name.startswith('java.') or name in known

    # The hand-written part of every bridge class, without its generated block
    tmp = tempfile.mkdtemp()
    try:
        src_tmp = os.path.join(tmp, 'src', 'org', 'lwjgl', 'sdl')
        os.makedirs(src_tmp)
        handwritten = {}
        for f in os.listdir(SRC):
            if not f.endswith('.java'): continue
            text = open(os.path.join(SRC, f), encoding='utf8').read()
            if BEGIN in text:
                if text.lstrip().startswith('/*\n * AMADORA: SDL3 on top of Amethyst\'s iOS GLFW layer, see AmadoraSDL. No hand-written'):
                    continue  # wholly generated: regenerated from scratch below
                text = text[:text.index(BEGIN)].rstrip() + '\n}\n'
            handwritten[f[:-5]] = text
            open(os.path.join(src_tmp, f), 'w', encoding='utf8').write(text)
        out = os.path.join(tmp, 'out')
        os.makedirs(out)
        lwjgl341 = [os.path.join(d, j) for d in ('JavaApp/lwjgl341', 'JavaApp/libs/others') for j in os.listdir(d) if j.endswith('.jar')]
        glfw = [os.path.join(dp, f) for dp, _, fs in os.walk('JavaApp/src_lwjgl341/org/lwjgl/glfw') for f in fs if f.endswith('.java')]
        subprocess.check_call([javac, '-nowarn', '-XDignore.symbol.file', '-implicit:none', '-proc:none',
                               '-sourcepath', 'JavaApp/src/launcher', '-cp', os.pathsep.join(lwjgl341), '-d', out]
                              + [os.path.join(src_tmp, f) for f in os.listdir(src_tmp)] + glfw)
        existing = {}
        for name in handwritten:
            path = os.path.join(out, 'org', 'lwjgl', 'sdl', name + '.class')
            fields, methods = parse_class(open(path, 'rb').read())
            existing[name] = ({f[1] for f in fields}, {(m[1], m[2]) for m in methods})
    finally:
        shutil.rmtree(tmp)

    with zipfile.ZipFile(sig_jar) as z:
        names = set(z.namelist())
        targets = sorted(n for n in names if re.fullmatch(r'org/lwjgl/sdl/SDL[A-Z]\w*\.class', n)
                         and n[:-6] + '$Functions.class' in names)
        report, computed = [], []
        for entry in targets:
            cls = entry[len('org/lwjgl/sdl/'):-6]
            fields, methods = parse_class(z.read(entry))
            have_fields, have_methods = existing.get(cls, (set(), set()))
            consts, stubs, skipped = [], [], 0
            for acc, name, desc, value in fields:
                if acc & ACC_PUBLIC and acc & ACC_STATIC and value is None and name not in have_fields:
                    computed.append('%s.%s' % (cls, name))  # set in <clinit>, so its value has to be hand-written
                if acc & ACC_PUBLIC and acc & ACC_STATIC and value is not None and name not in have_fields:
                    params, jtype = desc_types('()' + desc)
                    consts.append('    public static final %s %s = %s;' % (jtype, name, literal(desc, value)))
            for acc, name, desc, _ in methods:
                if not (acc & ACC_PUBLIC and acc & ACC_STATIC) or acc & ACC_SYNTHETIC or name == '<clinit>':
                    continue
                if (name, desc) in have_methods:
                    continue
                if not all(available(c) for c in class_refs(desc)):
                    skipped += 1
                    continue
                params, ret = desc_types(desc)
                args = ', '.join('%s p%d' % (t, i) for i, t in enumerate(params))
                body = 'AmadoraSDL.unsupported("%s");' % name
                if ret != 'void':
                    body += ' return %s;' % DEFAULTS.get(ret, 'null')
                stubs.append('    public static %s %s(%s) { %s }' % (ret, name, args, body))
            block = '\n'.join([BEGIN] + consts + ([''] if consts and stubs else []) + stubs + [END])
            path = os.path.join(SRC, cls + '.java')
            if cls in handwritten:
                text = handwritten[cls].rstrip()
                assert text.endswith('}'), path
                text = text[:-1].rstrip() + '\n\n' + block + '\n}\n'
            else:
                text = HEADER % (cls, cls, BEGIN, '\n'.join(consts + ([''] if consts and stubs else []) + stubs), END)
            open(path, 'w', encoding='utf8', newline='\n').write(text)
            report.append('%-22s %4d constants %4d defaults %3d skipped (types not in the runtime binding)%s'
                          % (cls, len(consts), len(stubs), skipped, '' if cls in handwritten else '  [new]'))
    print('\n'.join(report))
    if computed:
        print('Computed public fields, hand-write them outside the markers:\n  ' + '\n  '.join(computed))


if __name__ == '__main__':
    main()
